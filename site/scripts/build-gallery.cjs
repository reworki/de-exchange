'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const galleries = JSON.parse(fs.readFileSync(path.join(root, 'assets/img/gallery.json'), 'utf8'));
const source = '// Generated by scripts/build-gallery.cjs from assets/img/gallery.json.\n' +
  'var MARKET_GALLERY_DATA = ' + JSON.stringify(galleries) + ';\n';

fs.writeFileSync(path.join(root, 'assets/market-gallery-data.js'), source);
